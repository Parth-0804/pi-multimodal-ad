"""Recount the initial review's PA/SD codes; run from the thesis root."""

import argparse
import csv
import hashlib
import json
import re
from collections import Counter
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--outdir", type=Path, required=True)
    args = parser.parse_args()
    csv_path = Path("tables/literature_matrix.csv")
    tex_path = Path("tables/literature_matrix.tex")
    with csv_path.open(encoding="utf-8-sig", newline="") as source:
        rows = list(csv.DictReader(source))
    codes = {row["citation_key"]: row["missing_code"] for row in rows}
    tex_codes = dict(re.findall(
        r"\\(?:citep|parencite)\{([^}]+)\}\s*&[^&]+&[^&]+&[^&]+&\s*(\w+)\s*&",
        tex_path.read_text(),
    ))
    assert len(rows) == len(codes) == 37, "Initial 37-study cohort changed"
    assert codes == tex_codes, "CSV and printed appendix codes disagree"
    assert set(codes.values()) <= {"N", "NA", "PA", "SD", "TR", "GS", "RS"}
    selected = [row for row in rows if row["missing_code"] in {"PA", "SD"}]
    percentage = 100 * len(selected) / len(rows)
    audit = {
        "scope": "Recount of the initial 37-study appraisal matrix",
        "rule": "missing_code is PA (planned missing-input inference) or SD (simulated dropout)",
        "denominator": len(rows),
        "numerator": len(selected),
        "percentage": percentage,
        "display_percentage": f"{percentage:.1f}",
        "code_counts": dict(sorted(Counter(codes.values()).items())),
        "sources_sha256": {
            str(p): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in (csv_path, tex_path)
        },
        "records": [{k: row[k] for k in ("paper_id", "citation_key", "title", "missing_code")}
                    for row in rows],
        "selected_citation_keys": [row["citation_key"] for row in selected],
        "interpretation": "Coverage of PA/SD protocols in this initial cohort; not a fusion-benefit rate or field prevalence. Other missing-input regimes are coded separately.",
    }
    tex = (
        "% Generated by verify_review_coverage.py from the initial appraisal matrix.\n"
        f"\\newcommand{{\\InitialAppraisalCount}}{{{len(rows)}}}\n"
        f"\\newcommand{{\\AbsenceDropoutCount}}{{{len(selected)}}}\n"
        f"\\newcommand{{\\AbsenceDropoutPercent}}{{{percentage:.1f}}}\n"
    )
    args.outdir.mkdir(parents=True, exist_ok=True)
    for name, content in (("review_coverage.json", json.dumps(audit, indent=2) + "\n"),
                          ("review_coverage.tex", tex)):
        with (args.outdir / name).open("x") as output:
            output.write(content)
    print(f"PA/SD: {len(selected)}/{len(rows)} = {percentage:.1f}%")
    print("Codes:", audit["code_counts"])


if __name__ == "__main__":
    main()
